/**
 * React i18n binding: `useT()` returns a translator that re-renders when the
 * language setting changes. All Russian UI strings live in this file (English
 * text is written inline at call sites as the fallback).
 */
import { useCallback } from 'react'
import { registerMessages, translate } from './messages'
import type { TFunction } from './messages'
import { useStore } from './store'

export { registerMessages, translate } from './messages'
export type { Messages, TFunction } from './messages'

/** Reactive translator bound to the current language setting. */
export function useT(): TFunction {
  const lang = useStore((s) => s.settings.language)
  return useCallback(
    (key: string, fallback?: string) => translate(lang, key, fallback),
    [lang],
  )
}

